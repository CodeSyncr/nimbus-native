// The Go side of a project's native apps, built by `nimbus native lib` from
// the Xcode and Gradle projects: the IDE builds the host, the toolchain
// builds the Go library and the generated code it needs.

// IOSLib says what LibIOS builds, usually from Xcode's build settings.
type IOSLib struct {
	SDK   string   // iphonesimulator | iphoneos
	Archs []string // arm64, x86_64 (simulator only)
	MinOS string   // deployment target, e.g. "15.0"
	Out   string   // directory for libapp.a
	Swift string   // the generated Swift file to write, inside the app's sources
	Kit   string   // the project's copy of NimbusNativeKit, kept in sync ("" skips)
}

// AndroidLib says what LibAndroid builds, usually from Gradle.
type AndroidLib struct {
	ABIs   []string
	JNI    string // jniLibs directory: <abi>/libnimbusapp.so
	Kotlin string // source directory for the generated Kotlin
	Kit    string // the project's copy of the kit's Kotlin sources ("" skips)
}

// ErrKitUpdated means the project's copy of the host kit changed to match
// the nimbus-native version in go.mod; the IDE has to build again.
var ErrKitUpdated = errors.New("the native kit was updated to match go.mod; build again")

// LibIOS builds the app's Go code into libapp.a (one architecture, or a fat
// simulator library) and writes the generated Swift as one file.
func (e *Env) LibIOS(a *App, o IOSLib) error {
	if err := e.checkPhoneDeps(a); err != nil {
		return err
	}
	kitChanged, err := e.syncIOSKit(o.Kit, a.Root)
	if err != nil {
		return err
	}
	if err := e.writeSwift(a, o.Swift); err != nil {
		return err
	}

	if err := os.MkdirAll(o.Out, 0o755); err != nil {
		return err
	}
	lib := filepath.Join(o.Out, "libapp.a")
	var parts []string
	for _, arch := range o.Archs {
		e.step("go → libapp.a (ios/%s, %s)", arch, o.SDK)
		part := filepath.Join(o.Out, "libapp-"+arch+".a")
		if err := e.goIOS(a, o.SDK, arch, o.MinOS, part); err != nil {
			return err
		}
		parts = append(parts, part)
	}
	switch len(parts) {
	case 0:
		return fmt.Errorf("no architectures to build")
	case 1:
		err = os.Rename(parts[0], lib)
	default:
		err = e.run(nil, "lipo", append([]string{"-create", "-output", lib}, parts...)...)
		for _, p := range parts {
			os.Remove(p)
		}
	}
	if err != nil {
		return err
	}
	if kitChanged {
		return ErrKitUpdated
	}
	return nil
}

// writeSwift generates the app's Swift (its schemas and NimbusSchema) as
// one file, rewritten only when it changes so Xcode doesn't recompile.
func (e *Env) writeSwift(a *App, path string) error {
	generated, err := e.Gen(a)
	if err != nil {
		return err
	}
	var swift bytes.Buffer
	swift.WriteString("// Code generated by nimbus native lib; DO NOT EDIT.\n")
	for _, f := range generated.SwiftFiles {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		fmt.Fprintf(&swift, "\n// ---- %s\n", filepath.Base(f))
		swift.Write(b)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return writeIfChanged(path, swift.Bytes())
}

// LibAndroid builds libnimbusapp.so for each ABI and writes the generated
// Kotlin.
func (e *Env) LibAndroid(a *App, o AndroidLib) error {
	if e.NDK == "" {
		return fmt.Errorf("Android NDK not found (run doctor)")
	}
	if err := e.checkPhoneDeps(a); err != nil {
		return err
	}
	kitChanged, err := e.syncAndroidKit(o.Kit, a.Root)
	if err != nil {
		return err
	}
	generated, err := e.Gen(a)
	if err != nil {
		return err
	}
	files := map[string][]byte{}
	pkgDir := filepath.FromSlash(strings.ReplaceAll(a.ID, ".", "/"))
	for _, f := range generated.KotlinFiles {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		files[filepath.Join(pkgDir, filepath.Base(f))] = b
	}
	if _, err := syncDir(o.Kotlin, files); err != nil {
		return err
	}

	for _, name := range o.ABIs {
		abi, ok := AndroidABIs[name]
		if !ok {
			return fmt.Errorf("unknown ABI %q", name)
		}
		e.step("go → %s (android/%s)", androidLib, abi.Name)
		if err := e.goAndroid(a, abi, filepath.Join(o.JNI, abi.Name, androidLib)); err != nil {
			return err
		}
		os.Remove(filepath.Join(o.JNI, abi.Name, strings.TrimSuffix(androidLib, ".so")+".h"))
	}
	if kitChanged {
		return ErrKitUpdated
	}
	return nil
}

// syncIOSKit makes dir a Swift package of the iOS kit in this module, with
// the plugins the project at root enabled.
func (e *Env) syncIOSKit(dir, root string) (bool, error) {
	if dir == "" {
		return false, nil
	}
	header, err := os.ReadFile(filepath.Join(e.Repo, "bridge/include/nn.h"))
	if err != nil {
		return false, err
	}
	pkg, err := e.kitPackage(root)
	if err != nil {
		return false, err
	}
	files := map[string][]byte{"Package.swift": []byte(pkg), "Sources/NimbusNativeC/include/nn.h": header}
	src := filepath.Join(e.Repo, "hosts/ios/Sources")
	err = filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		name := filepath.Join("Sources", rel(src, p))
		if _, ok := files[name]; ok {
			return nil // the header comes from bridge/include
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		files[name] = b
		return nil
	})
	if err != nil {
		return false, err
	}
	if err := e.addPluginSources(root, "ios", "*.swift", "Sources/NimbusNativeKit/Plugins", enabledSwift, "Sources/NimbusNativeKit/EnabledPlugins.swift", files); err != nil {
		return false, err
	}
	return syncKit(dir, files)
}

// syncAndroidKit makes dir (a Kotlin source root) hold the Android kit and
// the plugins the project at root enabled.
func (e *Env) syncAndroidKit(dir, root string) (bool, error) {
	if dir == "" {
		return false, nil
	}
	files := map[string][]byte{}
	for _, p := range globs(filepath.Join(e.Repo, "hosts/android/src/space/nimbusgo/nativekit/*.kt")) {
		b, err := os.ReadFile(p)
		if err != nil {
			return false, err
		}
		files[filepath.Join("space/nimbusgo/nativekit", filepath.Base(p))] = b
	}
	if err := e.addPluginSources(root, "android", "*.kt", "space/nimbusgo/nativekit/plugins", enabledKotlin, "space/nimbusgo/nativekit/EnabledPlugins.kt", files); err != nil {
		return false, err
	}
	return syncKit(dir, files)
}

// syncKit is syncDir that reports a change only for a copy that existed: a
// fresh project gets its kit without a second build.
func syncKit(dir string, files map[string][]byte) (bool, error) {
	_, err := os.Stat(dir)
	fresh := os.IsNotExist(err)
	changed, err := syncDir(dir, files)
	return changed && !fresh, err
}

// syncDir makes dir hold exactly files (relative paths), leaving
// dot-directories (.swiftpm, .build) alone. It reports whether anything changed.
func syncDir(dir string, files map[string][]byte) (bool, error) {
	changed := false
	for name, b := range files {
		p := filepath.Join(dir, name)
		if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, b) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return false, err
		}
		if err := os.WriteFile(p, b, 0o644); err != nil {
			return false, err
		}
		changed = true
	}
	var stale []string
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			if p != dir && strings.HasPrefix(d.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if _, ok := files[rel(dir, p)]; !ok && !strings.HasPrefix(d.Name(), ".") {
			stale = append(stale, p)
		}
		return nil
	})
	for _, p := range stale {
		if err := os.Remove(p); err != nil {
			return false, err
		}
		changed = true
	}
	return changed, nil
}

