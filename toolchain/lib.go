// checkPhoneDeps refuses to build a project's phone app when it links
// server code: Nimbus itself, or any package of the project inside a
// directory named server. Server code stays on the server, and the phone
// binary stays small.
func (e *Env) checkPhoneDeps(a *App) error {
	if a.Root == "" {
		return nil
	}
	cmd := exec.Command("go", "list", "-deps", "-f", "{{.ImportPath}}|{{.Dir}}|{{join .Imports \" \"}}", ".")
	cmd.Dir = a.Dir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("go list: %w\n%s", err, stderr.String())
	}
	type pkg struct {
		dir     string
		imports []string
	}
	pkgs := map[string]pkg{}
	var entry string
	for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		f := strings.SplitN(l, "|", 3)
		if len(f) < 3 {
			continue
		}
		pkgs[f[0]] = pkg{f[1], strings.Fields(f[2])}
		entry = f[0] // -deps lists the package itself last
	}
	serverOnly := func(path string) bool {
		if path == "github.com/CodeSyncr/nimbus" || strings.HasPrefix(path, "github.com/CodeSyncr/nimbus/") {
			return true
		}
		d := pkgs[path].dir
		if !within(d, a.Root) {
			return false
		}
		for _, part := range strings.Split(filepath.ToSlash(rel(a.Root, d)), "/") {
			if part == "server" {
				return true
			}
		}
		return false
	}
	// Breadth-first from the entry, so the chain reported is the shortest.
	from := map[string]string{entry: ""}
	queue := []string{entry}
	for len(queue) > 0 {
		p := queue[0]
		queue = queue[1:]
		if serverOnly(p) {
			chain := []string{p}
			for q := from[p]; q != ""; q = from[q] {
				chain = append([]string{q}, chain...)
			}
			return fmt.Errorf("the phone app must not import server code:\n  %s\nkeep it behind an API (api.Endpoint) instead", strings.Join(chain, "\n  → "))
		}
		imports := append([]string(nil), pkgs[p].imports...)
		sort.Strings(imports)
		for _, i := range imports {
			if _, seen := from[i]; !seen {
				if _, ok := pkgs[i]; ok {
					from[i] = p
					queue = append(queue, i)
				}
			}
		}
	}
	return nil
}
