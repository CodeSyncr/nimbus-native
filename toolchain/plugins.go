// Optional plugins ship in plugins/ or are installed from Go modules into
// native/plugins/. A project lists enabled plugins in native/plugins.json;
// only their native sources and permissions reach its app.

// pluginList is a project's list of plugins, kept in order.
const pluginList = "native/plugins.json"

// pluginManifest is a plugin's plugin.json.
type pluginManifest struct {
	Name        string `json:"name"`
	Module      string `json:"module"`
	GoPackage   string `json:"go"`
	Description string `json:"description"`
	Handler     string `json:"handler"` // the Swift enum and Kotlin object with handle()
	Boot        bool   `json:"boot"`    // it has a boot() to run at launch
	// Needs are values the project supplies when it adds the plugin, such
	// as an API key: -key VALUE, used as {{key}} in what follows.
	Needs []string `json:"needs"`
	IOS   struct {
		// Info is what the app's Info.plist must say, such as the reason
		// iOS shows when it asks for a permission.
		Info map[string]string `json:"info"`
		// Arrays are Info.plist lists to add to.
		Arrays map[string][]string `json:"arrays"`
		// Entitlements go in Runner.entitlements.
		Entitlements map[string]string `json:"entitlements"`
		// EntitlementArrays are lists there.
		EntitlementArrays map[string][]string `json:"entitlementArrays"`
		// Packages are Swift packages for the kit.
		Packages []swiftPackage `json:"packages"`
		// ShareExtension adds a Share Extension target, from the plugin's
		// extension/ folder (shareext.go).
		ShareExtension bool `json:"shareExtension"`
	} `json:"ios"`
	Android struct {
		Permissions []string `json:"permissions"`
		// Application is XML for the app's <application>: its receivers
		// and providers.
		Application []string `json:"application"`
		// Dependencies are Gradle coordinates for the kit.
		Dependencies []string `json:"dependencies"`
		// Native are C libraries the plugin's Kotlin loads, built with the
		// NDK next to libnimbusapp.so (nativelib.go).
		Native []nativeLib `json:"native"`
	} `json:"android"`
}

// swiftPackage is a Swift package a plugin builds on.
type swiftPackage struct {
	URL     string `json:"url"`
	From    string `json:"from"`
	Package string `json:"package"`
	Product string `json:"product"`
}

func (e *Env) pluginDir(root, name string) string {
	local := filepath.Join(root, "native", "plugins", name)
	if exists(filepath.Join(local, "plugin.json")) {
		return local
	}
	return filepath.Join(e.Repo, "plugins", name)
}

func (e *Env) pluginManifest(root, name string) (*pluginManifest, error) {
	dir := e.pluginDir(root, name)
	b, err := os.ReadFile(filepath.Join(dir, "plugin.json"))
	if os.IsNotExist(err) {
		return nil, fmt.Errorf("no plugin named %q (nimbus native plugin list shows them)", name)
	}
	if err != nil {
		return nil, err
	}
	m := &pluginManifest{}
	if err := json.Unmarshal(b, m); err != nil {
		return nil, fmt.Errorf("%s/plugin.json: %w", dir, err)
	}
	if m.Name != "" && m.Name != name {
		return nil, fmt.Errorf("%s/plugin.json names %q, expected %q", dir, m.Name, name)
	}
	return m, nil
}

// enabledPlugins reads the project's list; a project without one has none.
func enabledPlugins(root string) ([]string, error) {
	b, err := os.ReadFile(filepath.Join(root, pluginList))
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	if err := json.Unmarshal(b, &names); err != nil {
		return nil, fmt.Errorf("%s: %w", pluginList, err)
	}
	return names, nil
}

func writePluginList(root string, names []string) error {
	if names == nil {
		names = []string{}
	}
	b, err := json.MarshalIndent(names, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, pluginList), append(b, '\n'), 0o644)
}

func enabledSwift(handlers map[string]string, boots, names []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by nimbus native lib; DO NOT EDIT.\n\nenum EnabledPlugins {\n    static func register() {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "        Plugins.register(%q, %s.handle)\n", n, handlers[n])
	}
	for _, h := range boots {
		fmt.Fprintf(&b, "        %s.boot()\n", h)
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

func enabledKotlin(handlers map[string]string, boots, names []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by nimbus native lib; DO NOT EDIT.\n\npackage space.nimbusgo.nativekit\n\ninternal object EnabledPlugins {\n    fun register() {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "        Plugins.register(%q, Plugins.Handler(%s::handle))\n", n, handlers[n])
	}
	for _, h := range boots {
		fmt.Fprintf(&b, "        %s.boot()\n", h)
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

// addPluginSources puts the enabled plugins' sources for a platform into
// files, under into, and the code that registers them at register.
func (e *Env) addPluginSources(root, platform, pattern, into string, gen func(map[string]string, []string, []string) string, register string, files map[string][]byte) error {
	names, err := enabledPlugins(root)
	if err != nil {
		return err
	}
	handlers := map[string]string{}
	var boots []string
	for _, n := range names {
		m, err := e.pluginManifest(root, n)
		if err != nil {
			return fmt.Errorf("%s: %w", pluginList, err)
		}
		handlers[n] = m.Handler
		if m.Boot {
			boots = append(boots, m.Handler)
		}
		for _, p := range globs(filepath.Join(e.pluginDir(root, n), platform, pattern)) {
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			files[filepath.Join(into, n, filepath.Base(p))] = b
		}
	}
	files[register] = []byte(gen(handlers, boots, names))
	if platform == "android" && slices.Contains(names, "push") {
		id, err := AndroidProjectID(root)
		if err != nil {
			return err
		}
		k, err := pushConfigKotlin(root, id)
		if err != nil {
			return err
		}
		files[filepath.Join(into, "push", "PushConfig.kt")] = []byte(k)
	}
	return nil
}

// ListPlugins shows the plugins that come with this version.
func (e *Env) ListPlugins(a *App, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	paths := globs(filepath.Join(e.Repo, "plugins/*/plugin.json"))
	sort.Strings(paths)
	for _, p := range paths {
		name := filepath.Base(filepath.Dir(p))
		m, err := e.pluginManifest(a.Root, name)
		if err != nil {
			return err
		}
		if slices.Contains(on, name) {
			Successf(out, "%-22s %s", name, m.Description)
		} else {
			fmt.Fprintf(out, "  %-22s %s\n", name, m.Description)
		}
	}
	local := globs(filepath.Join(a.Root, "native/plugins/*/plugin.json"))
	for _, p := range local {
		name := filepath.Base(filepath.Dir(p))
		if slices.ContainsFunc(paths, func(b string) bool { return filepath.Base(filepath.Dir(b)) == name }) {
			continue
		}
		m, err := e.pluginManifest(a.Root, name)
		if err != nil {
			return err
		}
		if slices.Contains(on, name) {
			Successf(out, "%-22s %s (third party)", name, m.Description)
		} else {
			fmt.Fprintf(out, "  %-22s %s (third party, installed)\n", name, m.Description)
		}
	}
	return nil
}

// AddPluginModules downloads plugin modules, stages their native handlers in
// the project, adds the Go dependency, then enables them like bundled plugins.
func (e *Env) AddPluginModules(a *App, modules []string, values map[string]string, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	for _, requested := range modules {
		module, _, hasVersion := strings.Cut(requested, "@")
		if module == "" || !strings.Contains(module, "/") {
			return fmt.Errorf("third-party plugin must be a Go module path, such as github.com/acme/nimbus-plugin-battery")
		}
		query := requested
		if !hasVersion {
			query += "@latest"
		}
		cmd := exec.Command("go", "list", "-m", "-json", query)
		cmd.Dir = a.Root
		b, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("resolve plugin module %s: %w", query, err)
		}
		var mod struct{ Path, Version, Dir string }
		if err := json.Unmarshal(b, &mod); err != nil {
			return fmt.Errorf("read plugin module %s: %w", query, err)
		}
		if mod.Dir == "" || mod.Path != module {
			return fmt.Errorf("Go did not resolve %s to a local module directory", query)
		}
		mb, err := os.ReadFile(filepath.Join(mod.Dir, "plugin.json"))
		if err != nil {
			return fmt.Errorf("%s must contain plugin.json: %w", module, err)
		}
		m := &pluginManifest{}
		if err := json.Unmarshal(mb, m); err != nil {
			return fmt.Errorf("%s/plugin.json: %w", module, err)
		}
		if m.Name == "" || !regexp.MustCompile(`^[a-z][a-z0-9]*$`).MatchString(m.Name) {
			return fmt.Errorf("%s/plugin.json must set name to lowercase letters and digits, starting with a letter", module)
		}
		if m.Handler == "" || m.Description == "" {
			return fmt.Errorf("%s/plugin.json must set handler and description", module)
		}
		if exists(filepath.Join(e.Repo, "plugins", m.Name, "plugin.json")) {
			return fmt.Errorf("plugin name %q is already used by Nimbus Native; choose another name", m.Name)
		}
		for _, platform := range []string{"ios", "android"} {
			pattern := "*.swift"
			if platform == "android" {
				pattern = "*.kt"
			}
			if len(globs(filepath.Join(mod.Dir, platform, pattern))) == 0 {
				return fmt.Errorf("%s needs at least one %s/%s handler", module, platform, pattern)
			}
		}
		if m.Module != "" && m.Module != module {
			return fmt.Errorf("%s/plugin.json module is %q, expected %q", module, m.Module, module)
		}
		m.Module = module
		staged := filepath.Join(a.Root, "native", "plugins", m.Name)
		if exists(filepath.Join(staged, "plugin.json")) {
			old, err := e.pluginManifest(a.Root, m.Name)
			if err != nil {
				return err
			}
			if old.Module != module {
				return fmt.Errorf("plugin name %q is already provided by %s", m.Name, old.Module)
			}
		}
		if err := stageExternalPlugin(mod.Dir, staged, m); err != nil {
			return err
		}
		versioned := module + "@" + mod.Version
		get := exec.Command("go", "get", versioned)
		get.Dir = a.Root
		if output, err := get.CombinedOutput(); err != nil {
			return fmt.Errorf("add plugin dependency %s: %s: %w", versioned, strings.TrimSpace(string(output)), err)
		}
		if err := e.AddPlugins(a, []string{m.Name}, values, out); err != nil {
			return err
		}
		Infof(out, "Import the Go API from %s (add a subpackage in plugin.json's go field if needed)", m.GoPackageOrModule())
	}
	return nil
}

func (m *pluginManifest) GoPackageOrModule() string {
	if m.GoPackage != "" {
		return m.GoPackage
	}
	return m.Module
}

func stageExternalPlugin(from, to string, m *pluginManifest) error {
	if err := os.MkdirAll(filepath.Join(to, "ios"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(to, "android"), 0o755); err != nil {
		return err
	}
	for platform, patterns := range map[string][]string{
		"ios":     {"*.swift"},
		"android": {"*.kt", "*.c", "*.h"},
	} {
		for _, pattern := range patterns {
			for _, stale := range globs(filepath.Join(to, platform, pattern)) {
				if err := os.Remove(stale); err != nil {
					return err
				}
			}
			for _, src := range globs(filepath.Join(from, platform, pattern)) {
				b, err := os.ReadFile(src)
				if err != nil {
					return err
				}
				if err := os.WriteFile(filepath.Join(to, platform, filepath.Base(src)), b, 0o644); err != nil {
					return err
				}
			}
		}
	}
	b, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(to, "plugin.json"), append(b, '\n'), 0o644)
}

// AddPlugins enables plugins: their sources reach the kit, and the app asks
// for what they need.
func (e *Env) AddPlugins(a *App, names []string, values map[string]string, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	for _, n := range names {
		m, err := e.pluginManifest(a.Root, n)
		if err != nil {
			return err
		}
		if slices.Contains(on, n) {
			// A newer version may need more, so adding it again catches up.
			// What it needs from the project stays as it was given.
			if len(m.Needs) > 0 {
				Infof(out, "%s is already in this project", n)
			} else if err := requirePlugin(a.Root, m); err != nil {
				return err
			} else if err := e.pluginExtras(a.Root, n, m); err != nil {
				return err
			} else {
				Infof(out, "%s is already in this project, and is up to date", n)
			}
			continue
		}
		for _, need := range m.Needs {
			if values[need] == "" {
				return fmt.Errorf("%s needs -%s: nimbus native plugin add %s -%s VALUE", n, need, n, need)
			}
		}
		if err := requirePlugin(a.Root, fill(m, values)); err != nil {
			return err
		}
		if err := e.pluginExtras(a.Root, n, m); err != nil {
			return err
		}
		on = append(on, n)
		Successf(out, "Added %s: %s", n, m.Description)
		for k := range m.IOS.Info {
			if strings.HasSuffix(k, "UsageDescription") {
				Infof(out, "Info.plist says why with %s: reword it for your app", k)
			}
		}
		if n == "push" && !exists(filepath.Join(a.Root, googleServices)) {
			Warnf(out, "Put your Firebase google-services.json at %s", googleServices)
		}
	}
	if err := writePluginList(a.Root, on); err != nil {
		return err
	}
	_, err = e.Sync(a)
	return err
}

// RemovePlugins disables plugins, and takes away what only they asked for.
func (e *Env) RemovePlugins(a *App, names []string, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	for _, n := range names {
		if !slices.Contains(on, n) {
			return fmt.Errorf("%s isn't in this project", n)
		}
		on = slices.DeleteFunc(on, func(x string) bool { return x == n })
	}
	keepInfo, keepPerm := map[string]bool{}, map[string]bool{}
	for _, n := range on {
		m, err := e.pluginManifest(a.Root, n)
		if err != nil {
			return err
		}
		for k := range m.IOS.Info {
			keepInfo[k] = true
		}
		for _, p := range m.Android.Permissions {
			keepPerm[p] = true
		}
	}
	for _, n := range names {
		m, err := e.pluginManifest(a.Root, n)
		if err != nil {
			return err
		}
		if err := dropPlugin(a.Root, m, keepInfo, keepPerm); err != nil {
			return err
		}
		if m.IOS.ShareExtension {
			if err := dropShareExtension(a.Root); err != nil {
				return err
			}
		}
		Successf(out, "Removed %s", n)
	}
	if err := writePluginList(a.Root, on); err != nil {
		return err
	}
	_, err = e.Sync(a)
	return err
}

const (
	projectPlist       = "native/ios/Runner/Info.plist"
	projectManifest    = "native/android/app/src/main/AndroidManifest.xml"
	projectKitGradle   = "native/android/nimbusnativekit/build.gradle.kts"
	projectGradleProps = "native/android/gradle.properties"
)

// edit rewrites a project file, if it's there: a project may have only one
// of the platforms.
func edit(root, name string, f func(string) string) error {
	p := filepath.Join(root, name)
	b, err := os.ReadFile(p)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if out := f(string(b)); out != string(b) {
		return os.WriteFile(p, []byte(out), 0o644)
	}
	return nil
}

// fill puts the project's values into a manifest's {{name}}s.
func fill(m *pluginManifest, values map[string]string) *pluginManifest {
	put := func(s string) string {
		for k, v := range values {
			s = strings.ReplaceAll(s, "{{"+k+"}}", xmlEscape(v))
		}
		return s
	}
	c := *m
	c.IOS.Info = map[string]string{}
	for k, v := range m.IOS.Info {
		for n, val := range values {
			v = strings.ReplaceAll(v, "{{"+n+"}}", val) // plistSet escapes
		}
		c.IOS.Info[k] = v
	}
	c.Android.Application = make([]string, len(m.Android.Application))
	for i, x := range m.Android.Application {
		c.Android.Application[i] = put(x)
	}
	return &c
}

// pluginExtras is what a plugin needs beyond manifest entries.
func (e *Env) pluginExtras(root, name string, m *pluginManifest) error {
	if m.IOS.ShareExtension {
		return e.addShareExtension(root, name)
	}
	return nil
}

func requirePlugin(root string, m *pluginManifest) error {
	if err := edit(root, projectPlist, func(s string) string {
		keys := make([]string, 0, len(m.IOS.Info))
		for k := range m.IOS.Info {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			s = plistSet(s, k, m.IOS.Info[k])
		}
		for k, list := range m.IOS.Arrays {
			s = plistAppend(s, k, list)
		}
		return s
	}); err != nil {
		return err
	}
	if len(m.IOS.Entitlements)+len(m.IOS.EntitlementArrays) > 0 {
		if err := writeEntitlements(root, m.IOS.Entitlements, m.IOS.EntitlementArrays); err != nil {
			return err
		}
	}
	if err := edit(root, projectKitGradle, func(s string) string {
		for _, d := range m.Android.Dependencies {
			s = gradleAdd(s, d)
		}
		return s
	}); err != nil {
		return err
	}
	if len(m.Android.Dependencies) > 0 {
		// Google's libraries bring AndroidX with them.
		if err := edit(root, projectGradleProps, func(s string) string {
			if strings.Contains(s, "android.useAndroidX") {
				return s
			}
			return strings.TrimRight(s, "\n") + "\nandroid.useAndroidX=true\n"
		}); err != nil {
			return err
		}
	}
	return edit(root, projectManifest, func(s string) string {
		for _, p := range m.Android.Permissions {
			s = manifestAdd(s, p)
		}
		for _, x := range m.Android.Application {
			s = applicationAdd(s, x)
		}
		return s
	})
}

func dropPlugin(root string, m *pluginManifest, keepInfo, keepPerm map[string]bool) error {
	if err := edit(root, projectPlist, func(s string) string {
		for k := range m.IOS.Info {
			if !keepInfo[k] {
				s = plistDrop(s, k)
			}
		}
		for k, list := range m.IOS.Arrays {
			s = plistRemove(s, k, list)
		}
		return s
	}); err != nil {
		return err
	}
	if len(m.IOS.Entitlements)+len(m.IOS.EntitlementArrays) > 0 {
		if err := dropEntitlements(root, m.IOS.Entitlements, m.IOS.EntitlementArrays); err != nil {
			return err
		}
	}
	if err := edit(root, projectKitGradle, func(s string) string {
		for _, d := range m.Android.Dependencies {
			s = gradleDrop(s, d)
		}
		return s
	}); err != nil {
		return err
	}
	return edit(root, projectManifest, func(s string) string {
		for _, p := range m.Android.Permissions {
			if !keepPerm[p] {
				s = manifestDrop(s, p)
			}
		}
		for _, x := range m.Android.Application {
			s = applicationDrop(s, x)
		}
		return s
	})
}

// applicationAdd puts a line of XML at the end of <application>.
func applicationAdd(s, xml string) string {
	if strings.Contains(s, xml) {
		return s
	}
	i := strings.LastIndex(s, "    </application>")
	if i < 0 {
		return s
	}
	return s[:i] + "        " + xml + "\n" + s[i:]
}

// applicationDrop removes a line applicationAdd put there; a {{value}} in it
// can be anything.
func applicationDrop(s, xml string) string {
	parts := regexp.MustCompile(`\{\{\w+\}\}`).Split(xml, -1)
	for i, p := range parts {
		parts[i] = regexp.QuoteMeta(p)
	}
	return regexp.MustCompile(`        `+strings.Join(parts, `[^"]*`)+`\n`).ReplaceAllString(s, "")
}

func gradleLine(dep string) string {
	return fmt.Sprintf("dependencies { implementation(%q) } // a plugin's\n", dep)
}

func gradleAdd(s, dep string) string {
	if strings.Contains(s, gradleLine(dep)) {
		return s
	}
	return strings.TrimRight(s, "\n") + "\n\n" + gradleLine(dep)
}

func gradleDrop(s, dep string) string {
	return strings.Replace(strings.Replace(s, "\n"+gradleLine(dep), "", 1), gradleLine(dep), "", 1)
}

// plistSet adds a key to an XML plist's top dict, keeping one already there:
// its wording belongs to the app.
func plistSet(s, key, value string) string {
	if strings.Contains(s, "<key>"+key+"</key>") {
		return s
	}
	i := strings.LastIndex(s, "</dict>")
	if i < 0 {
		return s
	}
	entry := fmt.Sprintf("\t<key>%s</key>\n\t<string>%s</string>\n", key, xmlEscape(value))
	return s[:i] + entry + s[i:]
}

func plistDrop(s, key string) string {
	re := regexp.MustCompile(`[ \t]*<key>` + regexp.QuoteMeta(key) + `</key>\s*<string>[^<]*</string>\n?`)
	return re.ReplaceAllString(s, "")
}

// plistAppend adds values to a list in the top dict, making it if needed.
func plistAppend(s, key string, values []string) string {
	head := "<key>" + key + "</key>"
	i := strings.Index(s, head)
	if i < 0 {
		end := strings.LastIndex(s, "</dict>")
		if end < 0 {
			return s
		}
		s = s[:end] + "\t" + head + "\n\t<array>\n\t</array>\n" + s[end:]
		i = strings.Index(s, head)
	}
	for _, v := range values {
		item := "<string>" + xmlEscape(v) + "</string>"
		close := i + strings.Index(s[i:], "</array>")
		if !strings.Contains(s[i:close], item) {
			s = s[:close] + "\t" + item + "\n\t" + s[close:]
		}
	}
	return s
}

// plistRemove takes values out of a list, and the list when it's empty.
func plistRemove(s, key string, values []string) string {
	for _, v := range values {
		s = regexp.MustCompile(`[ \t]*<string>`+regexp.QuoteMeta(xmlEscape(v))+`</string>\n`).ReplaceAllString(s, "")
	}
	return regexp.MustCompile(`[ \t]*<key>`+regexp.QuoteMeta(key)+`</key>\s*<array>\s*</array>\n?`).ReplaceAllString(s, "")
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// manifestAdd asks for a permission, after the manifest's opening tag.
func manifestAdd(s, permission string) string {
	if strings.Contains(s, `android:name="`+permission+`"`) {
		return s
	}
	line := fmt.Sprintf("    <uses-permission android:name=%q />\n", permission)
	if i := strings.LastIndex(s, "<uses-permission"); i >= 0 {
		end := strings.Index(s[i:], "\n")
		return s[:i+end+1] + line + s[i+end+1:]
	}
	i := strings.Index(s, "<manifest")
	if i < 0 {
		return s
	}
	end := strings.Index(s[i:], ">\n")
	if end < 0 {
		return s
	}
	return s[:i+end+2] + "\n" + line + s[i+end+2:]
}

func manifestDrop(s, permission string) string {
	re := regexp.MustCompile(`[ \t]*<uses-permission android:name="` + regexp.QuoteMeta(permission) + `"\s*/>\n?`)
	return re.ReplaceAllString(s, "")
}

const (
	projectEntitlements = "native/ios/Runner/Runner.entitlements"
	projectXcode        = "native/ios/Runner.xcodeproj/project.pbxproj"
	entitlementsSetting = "CODE_SIGN_ENTITLEMENTS = Runner/Runner.entitlements;"
)

// writeEntitlements adds to the app's entitlements, and points the Xcode
// project at the file.
func writeEntitlements(root string, values map[string]string, lists map[string][]string) error {
	p := filepath.Join(root, projectEntitlements)
	if !exists(filepath.Dir(p)) {
		return nil // no iOS app in this project
	}
	if !exists(p) {
		body := `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
</dict>
</plist>
`
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			return err
		}
	}
	if err := edit(root, projectEntitlements, func(s string) string {
		for k, v := range values {
			s = plistSet(s, k, v)
		}
		for k, l := range lists {
			s = plistAppend(s, k, l)
		}
		return s
	}); err != nil {
		return err
	}
	return edit(root, projectXcode, func(s string) string {
		if strings.Contains(s, entitlementsSetting) {
			return s
		}
		return strings.ReplaceAll(s, "CODE_SIGN_STYLE = Automatic;\n", "CODE_SIGN_STYLE = Automatic;\n\t\t\t\t"+entitlementsSetting+"\n")
	})
}

// dropEntitlements takes values out, and the file with them when it's empty.
func dropEntitlements(root string, values map[string]string, lists map[string][]string) error {
	if err := edit(root, projectEntitlements, func(s string) string {
		for k := range values {
			s = plistDrop(s, k)
		}
		for k, l := range lists {
			s = plistRemove(s, k, l)
		}
		return s
	}); err != nil {
		return err
	}
	b, err := os.ReadFile(filepath.Join(root, projectEntitlements))
	if err != nil || strings.Contains(string(b), "<key>") {
		return nil
	}
	if err := os.Remove(filepath.Join(root, projectEntitlements)); err != nil {
		return err
	}
	return edit(root, projectXcode, func(s string) string {
		return strings.ReplaceAll(s, "\t\t\t\t"+entitlementsSetting+"\n", "")
	})
}

// kitPackage is the kit's Package.swift, with what the enabled plugins need.
func (e *Env) kitPackage(root string) (string, error) {
	names, err := enabledPlugins(root)
	if err != nil {
		return "", err
	}
	var deps, products strings.Builder
	for _, n := range names {
		m, err := e.pluginManifest(root, n)
		if err != nil {
			return "", err
		}
		for _, p := range m.IOS.Packages {
			fmt.Fprintf(&deps, "        .package(url: %q, from: %q),\n", p.URL, p.From)
			fmt.Fprintf(&products, ", .product(name: %q, package: %q)", p.Product, p.Package)
		}
	}
	pkg := strings.Replace(kitPackageSwift, "    targets: [\n", "    dependencies: [\n"+deps.String()+"    ],\n    targets: [\n", 1)
	return strings.Replace(pkg, `dependencies: ["NimbusNativeC"]`, `dependencies: ["NimbusNativeC"`+products.String()+`]`, 1), nil
}

// googleServices is Android's Firebase settings, from the file the app's
// owner downloads from Firebase.
const googleServices = "native/android/app/google-services.json"

// pushConfigKotlin is the settings as code: Firebase starts from these, so
// the Gradle project needs no plugin of Google's.
func pushConfigKotlin(root, appID string) (string, error) {
	var appKey, projectID, sender, firebaseApp string
	b, err := os.ReadFile(filepath.Join(root, googleServices))
	if err != nil && !os.IsNotExist(err) {
		return "", err
	}
	if err == nil {
		var f struct {
			Project struct {
				Number string `json:"project_number"`
				ID     string `json:"project_id"`
			} `json:"project_info"`
			Client []struct {
				Info struct {
					ID      string `json:"mobilesdk_app_id"`
					Android struct {
						Package string `json:"package_name"`
					} `json:"android_client_info"`
				} `json:"client_info"`
				APIKey []struct {
					Current string `json:"current_key"`
				} `json:"api_key"`
			} `json:"client"`
		}
		if err := json.Unmarshal(b, &f); err != nil {
			return "", fmt.Errorf("%s: %w", googleServices, err)
		}
		found := false
		for _, c := range f.Client {
			if c.Info.Android.Package == appID && len(c.APIKey) > 0 {
				found, firebaseApp, appKey = true, c.Info.ID, c.APIKey[0].Current
				projectID, sender = f.Project.ID, f.Project.Number
			}
		}
		if !found {
			return "", fmt.Errorf("%s has no app for %s: add that package in Firebase and download it again", googleServices, appID)
		}
	}
	return fmt.Sprintf(`// Code generated by nimbus native lib from google-services.json; DO NOT EDIT.

package space.nimbusgo.nativekit

internal object PushConfig {
    const val APP_ID = %q
    const val API_KEY = %q
    const val PROJECT_ID = %q
    const val SENDER = %q
}
`, firebaseApp, appKey, projectID, sender), nil
}
