package toolchain

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

// Optional plugins: a folder in plugins/ with its Go API, plugin.json, and
// ios/ and android/ sources. A project lists the ones it uses in
// native/plugins.json; only those reach its app, with their permissions.
// The sources travel with the kit (syncIOSKit, syncAndroidKit), so the Xcode
// and Gradle projects don't change.

// pluginList is a project's list of plugins, kept in order.
const pluginList = "native/plugins.json"

// pluginManifest is a plugin's plugin.json.
type pluginManifest struct {
	Description string `json:"description"`
	Handler     string `json:"handler"` // the Swift enum and Kotlin object with handle()
	IOS         struct {
		// Info is what the app's Info.plist must say, such as the reason
		// iOS shows when it asks for a permission.
		Info map[string]string `json:"info"`
	} `json:"ios"`
	Android struct {
		Permissions []string `json:"permissions"`
	} `json:"android"`
}

func (e *Env) pluginManifest(name string) (*pluginManifest, error) {
	b, err := os.ReadFile(filepath.Join(e.Repo, "plugins", name, "plugin.json"))
	if os.IsNotExist(err) {
		return nil, fmt.Errorf("no plugin named %q (nimbus native plugin list shows them)", name)
	}
	if err != nil {
		return nil, err
	}
	m := &pluginManifest{}
	if err := json.Unmarshal(b, m); err != nil {
		return nil, fmt.Errorf("plugins/%s/plugin.json: %w", name, err)
	}
	return m, nil
}

// enabledPlugins reads the project's list; a project without one has none.
func enabledPlugins(root string) ([]string, error) {
	b, err := os.ReadFile(filepath.Join(root, pluginList))
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	if err := json.Unmarshal(b, &names); err != nil {
		return nil, fmt.Errorf("%s: %w", pluginList, err)
	}
	return names, nil
}

func writePluginList(root string, names []string) error {
	if names == nil {
		names = []string{}
	}
	b, err := json.MarshalIndent(names, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, pluginList), append(b, '\n'), 0o644)
}

func enabledSwift(handlers map[string]string, names []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by nimbus native lib; DO NOT EDIT.\n\nenum EnabledPlugins {\n    static func register() {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "        Plugins.register(%q, %s.handle)\n", n, handlers[n])
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

func enabledKotlin(handlers map[string]string, names []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by nimbus native lib; DO NOT EDIT.\n\npackage space.nimbusgo.nativekit\n\ninternal object EnabledPlugins {\n    fun register() {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "        Plugins.register(%q, Plugins.Handler(%s::handle))\n", n, handlers[n])
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

// addPluginSources puts the enabled plugins' sources for a platform into
// files, under into, and the code that registers them at register.
func (e *Env) addPluginSources(root, platform, pattern, into string, gen func(map[string]string, []string) string, register string, files map[string][]byte) error {
	names, err := enabledPlugins(root)
	if err != nil {
		return err
	}
	handlers := map[string]string{}
	for _, n := range names {
		m, err := e.pluginManifest(n)
		if err != nil {
			return fmt.Errorf("%s: %w", pluginList, err)
		}
		handlers[n] = m.Handler
		for _, p := range globs(filepath.Join(e.Repo, "plugins", n, platform, pattern)) {
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			files[filepath.Join(into, n, filepath.Base(p))] = b
		}
	}
	files[register] = []byte(gen(handlers, names))
	return nil
}

// ListPlugins shows the plugins that come with this version.
func (e *Env) ListPlugins(a *App, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	paths := globs(filepath.Join(e.Repo, "plugins/*/plugin.json"))
	sort.Strings(paths)
	for _, p := range paths {
		name := filepath.Base(filepath.Dir(p))
		m, err := e.pluginManifest(name)
		if err != nil {
			return err
		}
		if slices.Contains(on, name) {
			Successf(out, "%-22s %s", name, m.Description)
		} else {
			fmt.Fprintf(out, "  %-22s %s\n", name, m.Description)
		}
	}
	return nil
}

// AddPlugins enables plugins: their sources reach the kit, and the app asks
// for what they need.
func (e *Env) AddPlugins(a *App, names []string, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	for _, n := range names {
		m, err := e.pluginManifest(n)
		if err != nil {
			return err
		}
		if slices.Contains(on, n) {
			Infof(out, "%s is already in this project", n)
			continue
		}
		if err := requirePlugin(a.Root, m); err != nil {
			return err
		}
		on = append(on, n)
		Successf(out, "Added %s: %s", n, m.Description)
		for k := range m.IOS.Info {
			Infof(out, "Info.plist says why with %s: reword it for your app", k)
		}
	}
	if err := writePluginList(a.Root, on); err != nil {
		return err
	}
	_, err = e.Sync(a)
	return err
}

// RemovePlugins disables plugins, and takes away what only they asked for.
func (e *Env) RemovePlugins(a *App, names []string, out io.Writer) error {
	if e.Repo = moduleDir(a.Root); e.Repo == "" {
		return fmt.Errorf("nimbus-native module not found from %s", a.Root)
	}
	on, err := enabledPlugins(a.Root)
	if err != nil {
		return err
	}
	for _, n := range names {
		if !slices.Contains(on, n) {
			return fmt.Errorf("%s isn't in this project", n)
		}
		on = slices.DeleteFunc(on, func(x string) bool { return x == n })
	}
	keepInfo, keepPerm := map[string]bool{}, map[string]bool{}
	for _, n := range on {
		m, err := e.pluginManifest(n)
		if err != nil {
			return err
		}
		for k := range m.IOS.Info {
			keepInfo[k] = true
		}
		for _, p := range m.Android.Permissions {
			keepPerm[p] = true
		}
	}
	for _, n := range names {
		m, err := e.pluginManifest(n)
		if err != nil {
			return err
		}
		if err := dropPlugin(a.Root, m, keepInfo, keepPerm); err != nil {
			return err
		}
		Successf(out, "Removed %s", n)
	}
	if err := writePluginList(a.Root, on); err != nil {
		return err
	}
	_, err = e.Sync(a)
	return err
}

const (
	projectPlist    = "native/ios/Runner/Info.plist"
	projectManifest = "native/android/app/src/main/AndroidManifest.xml"
)

// edit rewrites a project file, if it's there: a project may have only one
// of the platforms.
func edit(root, name string, f func(string) string) error {
	p := filepath.Join(root, name)
	b, err := os.ReadFile(p)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if out := f(string(b)); out != string(b) {
		return os.WriteFile(p, []byte(out), 0o644)
	}
	return nil
}

func requirePlugin(root string, m *pluginManifest) error {
	if err := edit(root, projectPlist, func(s string) string {
		keys := make([]string, 0, len(m.IOS.Info))
		for k := range m.IOS.Info {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			s = plistSet(s, k, m.IOS.Info[k])
		}
		return s
	}); err != nil {
		return err
	}
	return edit(root, projectManifest, func(s string) string {
		for _, p := range m.Android.Permissions {
			s = manifestAdd(s, p)
		}
		return s
	})
}

func dropPlugin(root string, m *pluginManifest, keepInfo, keepPerm map[string]bool) error {
	if err := edit(root, projectPlist, func(s string) string {
		for k := range m.IOS.Info {
			if !keepInfo[k] {
				s = plistDrop(s, k)
			}
		}
		return s
	}); err != nil {
		return err
	}
	return edit(root, projectManifest, func(s string) string {
		for _, p := range m.Android.Permissions {
			if !keepPerm[p] {
				s = manifestDrop(s, p)
			}
		}
		return s
	})
}

// plistSet adds a key to an XML plist's top dict, keeping one already there:
// its wording belongs to the app.
func plistSet(s, key, value string) string {
	if strings.Contains(s, "<key>"+key+"</key>") {
		return s
	}
	i := strings.LastIndex(s, "</dict>")
	if i < 0 {
		return s
	}
	entry := fmt.Sprintf("\t<key>%s</key>\n\t<string>%s</string>\n", key, xmlEscape(value))
	return s[:i] + entry + s[i:]
}

func plistDrop(s, key string) string {
	re := regexp.MustCompile(`[ \t]*<key>` + regexp.QuoteMeta(key) + `</key>\s*<string>[^<]*</string>\n?`)
	return re.ReplaceAllString(s, "")
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// manifestAdd asks for a permission, after the manifest's opening tag.
func manifestAdd(s, permission string) string {
	if strings.Contains(s, `android:name="`+permission+`"`) {
		return s
	}
	line := fmt.Sprintf("    <uses-permission android:name=%q />\n", permission)
	if i := strings.LastIndex(s, "<uses-permission"); i >= 0 {
		end := strings.Index(s[i:], "\n")
		return s[:i+end+1] + line + s[i+end+1:]
	}
	i := strings.Index(s, "<manifest")
	if i < 0 {
		return s
	}
	end := strings.Index(s[i:], ">\n")
	if end < 0 {
		return s
	}
	return s[:i+end+2] + "\n" + line + s[i+end+2:]
}

func manifestDrop(s, permission string) string {
	re := regexp.MustCompile(`[ \t]*<uses-permission android:name="` + regexp.QuoteMeta(permission) + `"\s*/>\n?`)
	return re.ReplaceAllString(s, "")
}
