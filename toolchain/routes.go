// Folder routing: every directory under pages/ with a page.go is a route,
// and a directory named _name is the parameter name. GenRoutes writes the
// static table (pages/routes_gen.go) that package router matches against.

// RoutesFile is the generated table, in the pages package.
const RoutesFile = "routes_gen.go"

type page struct {
	dir     string // relative to pages/, slash-separated ("orders/_id")
	pattern string // "/orders/:id"
	pkg     string // package name
	alias   string // import alias ("" for the pages package itself)
	params  []pageParam
}

type pageParam struct {
	name, field, typ string // "id", "ID", "int"
}

var segmentName = regexp.MustCompile(`^[a-z0-9][a-z0-9\-]*$`)

// GenRoutes generates pages/routes_gen.go for the module at root. It does
// nothing when there is no pages directory.
func (e *Env) GenRoutes(root string) error {
	pagesDir := filepath.Join(root, "pages")
	if fi, err := os.Stat(pagesDir); err != nil || !fi.IsDir() {
		return nil
	}
	module, err := modulePath(root)
	if err != nil {
		return err
	}
	var pages []page
	params := map[string]string{} // parent dir → its parameter folder, to catch siblings
	err = filepath.WalkDir(pagesDir, func(p string, d os.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return err
		}
		rel := filepath.ToSlash(strings.TrimPrefix(strings.TrimPrefix(p, pagesDir), string(filepath.Separator)))
		name := d.Name()
		if p != pagesDir {
			if strings.HasPrefix(name, ".") || name == "testdata" {
				return filepath.SkipDir
			}
			seg := strings.TrimPrefix(name, "_")
			if !segmentName.MatchString(seg) {
				return fmt.Errorf("pages/%s: a route folder is lower-case letters, digits and dashes (or _name for a parameter)", rel)
			}
			if strings.HasPrefix(name, "_") {
				parent := filepath.Dir(p)
				if other, ok := params[parent]; ok {
					return fmt.Errorf("pages/%s and %s: one folder can hold only one parameter folder", rel, other)
				}
				params[parent] = name
			}
		}
		if !exists(filepath.Join(p, "page.go")) {
			return nil
		}
		pg, err := readPage(p, rel)
		if err != nil {
			return err
		}
		pages = append(pages, pg)
		return nil
	})
	if err != nil {
		return err
	}

	pkg := "pages"
	var imports []string
	aliases := map[string]bool{}
	for i := range pages {
		pg := &pages[i]
		if pg.dir == "" {
			pkg = pg.pkg
			continue
		}
		// p_orders_id for pages/orders/_id: never a keyword or another import.
		pg.alias = "p_" + strings.NewReplacer("/_", "_", "/", "_", "-", "_").Replace(strings.TrimPrefix(pg.dir, "_"))
		for n := 2; aliases[pg.alias]; n++ {
			pg.alias = strings.TrimRight(pg.alias, "0123456789") + strconv.Itoa(n)
		}
		aliases[pg.alias] = true
		imports = append(imports, fmt.Sprintf("%s %q", pg.alias, module+"/pages/"+pg.dir))
	}
	if pkg == "pages" {
		// No root page: use the package other files in pages/ declare, if any.
		if name := packageName(pagesDir); name != "" {
			pkg = name
		}
	}
	sort.Slice(pages, func(i, j int) bool { return pages[i].pattern < pages[j].pattern })
	sort.Strings(imports)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by nimbus native gen from the folders in pages/. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	b.WriteString("import (\n\t\"github.com/CodeSyncr/nimbus-native/router\"\n\t\"github.com/CodeSyncr/nimbus-native/ui\"\n")
	if len(imports) > 0 {
		b.WriteString("\n\t" + strings.Join(imports, "\n\t") + "\n")
	}
	b.WriteString(")\n\n// Routes is every page under pages/; pass it to router.Register.\nvar Routes = router.Table{\n")
	for _, pg := range pages {
		typ := "Page"
		if pg.alias != "" {
			typ = pg.alias + ".Page"
		}
		if len(pg.params) == 0 {
			fmt.Fprintf(&b, "\t{Pattern: %q, New: func(router.Params) (ui.Component, bool) { return %s{}, true }},\n", pg.pattern, typ)
			continue
		}
		fmt.Fprintf(&b, "\t{Pattern: %q, New: func(p router.Params) (ui.Component, bool) {\n", pg.pattern)
		var fields []string
		for i, pp := range pg.params {
			switch pp.typ {
			case "string":
				fields = append(fields, fmt.Sprintf("%s: p.Get(%q)", pp.field, pp.name))
			default: // int, int64
				v := "v" + strconv.Itoa(i)
				method := map[string]string{"int": "Int", "int64": "Int64"}[pp.typ]
				fmt.Fprintf(&b, "\t\t%s, ok := p.%s(%q)\n\t\tif !ok {\n\t\t\treturn nil, false\n\t\t}\n", v, method, pp.name)
				fields = append(fields, fmt.Sprintf("%s: %s", pp.field, v))
			}
		}
		fmt.Fprintf(&b, "\t\treturn %s{%s}, true\n\t}},\n", typ, strings.Join(fields, ", "))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("routes: %w\n%s", err, b.Bytes())
	}
	e.step("gen pages/ → %s (%d routes)", RoutesFile, len(pages))
	return writeIfChanged(filepath.Join(pagesDir, RoutesFile), src)
}

// readPage reads a page folder's Page type and checks its parameters
// against the folder's path.
func readPage(dir, rel string) (page, error) {
	pg := page{dir: rel, pattern: "/"}
	var want []string
	if rel != "" {
		var segs []string
		for _, s := range strings.Split(rel, "/") {
			if strings.HasPrefix(s, "_") {
				want = append(want, s[1:])
				s = ":" + s[1:]
			}
			segs = append(segs, s)
		}
		pg.pattern = "/" + strings.Join(segs, "/")
	}
	where := "pages/" + rel
	if rel == "" {
		where = "pages"
	}

	fset := token.NewFileSet()
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	var st *ast.StructType
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || filepath.Base(f) == RoutesFile {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, parser.SkipObjectResolution)
		if err != nil {
			return pg, err
		}
		pg.pkg = file.Name.Name
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				if ts.Name.Name != "Page" {
					continue
				}
				if st, ok = ts.Type.(*ast.StructType); !ok {
					return pg, fmt.Errorf("%s: Page must be a struct type", where)
				}
			}
		}
	}
	if st == nil {
		return pg, fmt.Errorf("%s/page.go: declare the page as type Page struct{...} with a Render method", where)
	}

	got := map[string]bool{}
	for _, f := range st.Fields.List {
		if f.Tag == nil {
			continue
		}
		tag, _ := strconv.Unquote(f.Tag.Value)
		name := reflect.StructTag(tag).Get("param")
		if name == "" {
			continue
		}
		if len(f.Names) != 1 {
			return pg, fmt.Errorf("%s: tag one field per param:%q", where, name)
		}
		id, ok := f.Type.(*ast.Ident)
		if !ok || (id.Name != "string" && id.Name != "int" && id.Name != "int64") {
			return pg, fmt.Errorf("%s: Page.%s (param %q) must be a string, int or int64", where, f.Names[0].Name, name)
		}
		if !contains(want, name) {
			return pg, fmt.Errorf("%s: Page.%s wants param %q, but the path %s has no _%s folder", where, f.Names[0].Name, name, pg.pattern, name)
		}
		got[name] = true
		pg.params = append(pg.params, pageParam{name: name, field: f.Names[0].Name, typ: id.Name})
	}
	for _, name := range want {
		if !got[name] {
			return pg, fmt.Errorf("%s: Page needs a field tagged `param:%q` for the _%s folder", where, name, name)
		}
	}
	return pg, nil
}

// packageName is the package the Go files in dir declare, or "".
func packageName(dir string) string {
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range files {
		if filepath.Base(f) == RoutesFile {
			continue
		}
		if file, err := parser.ParseFile(token.NewFileSet(), f, nil, parser.PackageClauseOnly); err == nil {
			return file.Name.Name
		}
	}
	return ""
}

func modulePath(root string) (string, error) {
	b, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, l := range strings.Split(string(b), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(l), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("no module line in %s/go.mod", root)
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}
