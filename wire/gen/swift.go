package gen

import (
	"fmt"
	"strings"

	"github.com/CodeSyncr/nimbus-native/wire/schema"
)

// Swift generates the schema's types for iOS hosts, inside one namespace
// enum named after the package (package proto → enum Proto). It needs the
// NimbusNativeKit wire runtime (Wire.swift) in the same module.
func Swift(s *schema.Schema) []byte {
	g := &swiftGen{s: s}
	ns := namespace(s)
	g.p(0, "// Code generated by nimbus-native gen. DO NOT EDIT.")
	g.p(0, "// Schema: %s", s.Dir)
	g.p(0, "")
	g.p(0, "public enum %s {", ns)
	g.p(1, "/// Identifies this schema's wire layout; must match the Go side.")
	g.p(1, "public static let schemaHash: UInt64 = %#016x", s.Hash)
	for _, e := range s.Enums {
		g.enum(e)
	}
	for _, st := range s.Structs {
		g.structDef(st)
	}
	for _, u := range s.Unions {
		g.union(u.Name, u.Doc, u.Variants, false)
	}
	g.union(schema.MessageUnion, "Any top-level message in this schema.", s.Messages, true)
	g.p(0, "}")
	return []byte(g.b.String())
}

// SwiftSchema generates the file that tells the host which combined schema
// hash to pass to nn_start.
func SwiftSchema(combined uint64) []byte {
	return []byte(fmt.Sprintf(`// Code generated by nimbus-native gen. DO NOT EDIT.

/// The combined hash of every wire schema linked into this app. Bridge.start
/// passes it to the Go runtime, which refuses to start on a mismatch.
public enum NimbusSchema {
    public static let combined: UInt64 = %#016x
}
`, combined))
}

type swiftGen struct {
	s *schema.Schema
	b strings.Builder
}

func (g *swiftGen) p(indent int, format string, args ...any) {
	if format != "" {
		g.b.WriteString(strings.Repeat("    ", indent))
		fmt.Fprintf(&g.b, format, args...)
	}
	g.b.WriteByte('\n')
}

func (g *swiftGen) doc(indent int, doc string) {
	for _, l := range strings.Split(doc, "\n") {
		if l != "" {
			g.p(indent, "/// %s", l)
		}
	}
}

func (g *swiftGen) enum(e *schema.EnumDef) {
	base := swiftInt(e.Bits, e.Signed)
	g.p(0, "")
	g.doc(1, e.Doc)
	g.p(1, "public struct %s: RawRepresentable, Equatable, Hashable {", e.Name)
	g.p(2, "public var rawValue: %s", base)
	g.p(2, "public init(rawValue: %s) { self.rawValue = rawValue }", base)
	for _, v := range e.Values {
		lit := fmt.Sprint(v.Value)
		if !e.Signed {
			lit = fmt.Sprint(uint64(v.Value))
		}
		g.p(2, "public static let %s = %s(rawValue: %s)", swiftName(enumConst(e, v)), e.Name, lit)
	}
	g.p(1, "}")
}

func (g *swiftGen) structDef(st *schema.StructDef) {
	g.p(0, "")
	g.doc(1, st.Doc)
	g.p(1, "public struct %s: Equatable {", st.Name)
	var params, assigns []string
	for _, f := range st.Fields {
		n := swiftName(f.Name)
		g.p(2, "public var %s: %s", n, swiftType(f.Type))
		params = append(params, fmt.Sprintf("%s: %s = %s", n, swiftType(f.Type), swiftDefault(f.Type)))
		assigns = append(assigns, fmt.Sprintf("self.%s = %s", n, n))
	}
	g.p(0, "")
	g.p(2, "public init(%s) {", strings.Join(params, ", "))
	for _, a := range assigns {
		g.p(3, "%s", a)
	}
	g.p(2, "}")
	g.p(0, "")
	g.p(2, "public func write(to w: inout WireWriter) {")
	for _, f := range st.Fields {
		g.write(3, f.Type, "self."+swiftName(f.Name), 0)
	}
	g.p(2, "}")
	g.p(0, "")
	g.p(2, "public static func read(from r: inout WireReader) throws -> %s {", st.Name)
	g.p(3, "var m = %s()", st.Name)
	for _, f := range st.Fields {
		g.p(3, "m.%s = %s", swiftName(f.Name), swiftRead(f.Type))
	}
	g.p(3, "return m")
	g.p(2, "}")
	g.p(1, "}")
}

func (g *swiftGen) union(name, doc string, variants []string, message bool) {
	g.p(0, "")
	g.doc(1, doc)
	g.p(1, "public indirect enum %s: Equatable {", name)
	for _, v := range variants {
		g.p(2, "case %s(%s)", swiftName(v), v)
	}
	g.p(0, "")
	g.p(2, "public static func write(_ v: %s?, to w: inout WireWriter) {", name)
	g.p(3, "switch v {")
	g.p(3, "case nil:")
	g.p(4, "w.uint(0)")
	for i, v := range variants {
		g.p(3, "case .%s(let x)?:", strings.Trim(swiftName(v), "`"))
		g.p(4, "w.uint(%d)", i+1)
		g.p(4, "x.write(to: &w)")
	}
	g.p(3, "}")
	g.p(2, "}")
	g.p(0, "")
	g.p(2, "public static func read(from r: inout WireReader) throws -> %s? {", name)
	g.p(3, "switch try r.uint() {")
	g.p(3, "case 0:")
	g.p(4, "return nil")
	for i, v := range variants {
		g.p(3, "case %d:", i+1)
		g.p(4, "return .%s(try %s.read(from: &r))", strings.Trim(swiftName(v), "`"), v)
	}
	g.p(3, "default:")
	g.p(4, "throw WireError.variant")
	g.p(3, "}")
	g.p(2, "}")
	if message {
		g.p(0, "")
		g.p(2, "/// The message's wire encoding: its id, then its fields.")
		g.p(2, "public func encode() -> [UInt8] {")
		g.p(3, "var w = WireWriter()")
		g.p(3, "%s.write(self, to: &w)", name)
		g.p(3, "return w.bytes")
		g.p(2, "}")
		g.p(0, "")
		g.p(2, "/// Reads exactly one message.")
		g.p(2, "public static func decode(_ bytes: [UInt8]) throws -> %s {", name)
		g.p(3, "var r = WireReader(bytes)")
		g.p(3, "guard let m = try read(from: &r) else { throw WireError.variant }")
		g.p(3, "try r.done()")
		g.p(3, "return m")
		g.p(2, "}")
	}
	g.p(1, "}")
}

func (g *swiftGen) write(indent int, t *schema.Type, x string, depth int) {
	switch t.Kind {
	case schema.Bool:
		g.p(indent, "w.bool(%s)", x)
	case schema.Uint:
		g.p(indent, "w.uint(UInt64(%s))", x)
	case schema.Int:
		g.p(indent, "w.int(Int64(%s))", x)
	case schema.Float32:
		g.p(indent, "w.float32(%s)", x)
	case schema.Float64:
		g.p(indent, "w.float64(%s)", x)
	case schema.String:
		g.p(indent, "w.string(%s)", x)
	case schema.Bytes:
		g.p(indent, "w.bytes(%s)", x)
	case schema.Enum:
		if t.Signed {
			g.p(indent, "w.int(Int64(%s.rawValue))", x)
		} else {
			g.p(indent, "w.uint(UInt64(%s.rawValue))", x)
		}
	case schema.Struct:
		g.p(indent, "%s.write(to: &w)", x)
	case schema.Union:
		g.p(indent, "%s.write(%s, to: &w)", t.Name, x)
	case schema.Optional:
		v := fmt.Sprintf("o%d", depth)
		g.p(indent, "if let %s = %s {", v, x)
		g.p(indent+1, "w.bool(true)")
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "} else {")
		g.p(indent+1, "w.bool(false)")
		g.p(indent, "}")
	case schema.List:
		v := fmt.Sprintf("v%d", depth)
		g.p(indent, "w.uint(UInt64(%s.count))", x)
		g.p(indent, "for %s in %s {", v, x)
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "}")
	case schema.Map:
		k, v := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth)
		g.p(indent, "w.uint(UInt64(%s.count))", x)
		g.p(indent, "for %s in WireWriter.sortedKeys(%s) {", k, x)
		g.write(indent+1, t.Key, k, depth+1)
		g.p(indent+1, "let %s = %s[%s]!", v, x, k)
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "}")
	}
}

// swiftRead is an expression that reads t from the WireReader named r.
func swiftRead(t *schema.Type) string {
	switch t.Kind {
	case schema.Bool:
		return "try r.bool()"
	case schema.Uint:
		if t.Bits == 64 {
			return "try r.uint()"
		}
		return fmt.Sprintf("%s(try r.uint(max: %d))", swiftInt(t.Bits, false), uint64(1)<<t.Bits-1)
	case schema.Int:
		return swiftReadInt(t.Bits)
	case schema.Float32:
		return "try r.float32()"
	case schema.Float64:
		return "try r.float64()"
	case schema.String:
		return "try r.string()"
	case schema.Bytes:
		return "try r.bytes()"
	case schema.Enum:
		inner := swiftReadInt(t.Bits)
		if !t.Signed {
			inner = swiftRead(&schema.Type{Kind: schema.Uint, Bits: t.Bits})
		}
		return fmt.Sprintf("%s(rawValue: %s)", t.Name, inner)
	case schema.Struct, schema.Union:
		return fmt.Sprintf("try %s.read(from: &r)", t.Name)
	case schema.Optional:
		return fmt.Sprintf("(try r.bool() ? %s : nil)", swiftRead(t.Elem))
	case schema.List:
		return fmt.Sprintf("try r.list { r in %s }", swiftRead(t.Elem))
	case schema.Map:
		return fmt.Sprintf("try r.map({ r in %s }, { r in %s })", swiftRead(t.Key), swiftRead(t.Elem))
	}
	panic("unreachable")
}

func swiftReadInt(bits int) string {
	if bits == 64 {
		return "try r.int()"
	}
	return fmt.Sprintf("%s(try r.int(min: %d, max: %d))", swiftInt(bits, true), -(int64(1) << (bits - 1)), int64(1)<<(bits-1)-1)
}

func swiftType(t *schema.Type) string {
	switch t.Kind {
	case schema.Bool:
		return "Bool"
	case schema.Uint:
		return swiftInt(t.Bits, false)
	case schema.Int:
		return swiftInt(t.Bits, true)
	case schema.Float32:
		return "Float"
	case schema.Float64:
		return "Double"
	case schema.String:
		return "String"
	case schema.Bytes:
		return "[UInt8]"
	case schema.List:
		return "[" + swiftType(t.Elem) + "]"
	case schema.Map:
		return "[" + swiftType(t.Key) + ": " + swiftType(t.Elem) + "]"
	case schema.Optional:
		return swiftType(t.Elem) + "?"
	case schema.Union:
		return t.Name + "?"
	}
	return t.Name // Struct, Enum
}

func swiftDefault(t *schema.Type) string {
	switch t.Kind {
	case schema.Bool:
		return "false"
	case schema.Uint, schema.Int, schema.Float32, schema.Float64:
		return "0"
	case schema.String:
		return `""`
	case schema.Bytes, schema.List:
		return "[]"
	case schema.Map:
		return "[:]"
	case schema.Optional, schema.Union:
		return "nil"
	case schema.Enum:
		return t.Name + "(rawValue: 0)"
	}
	return t.Name + "()"
}

func swiftInt(bits int, signed bool) string {
	if signed {
		return fmt.Sprintf("Int%d", bits)
	}
	return fmt.Sprintf("UInt%d", bits)
}
