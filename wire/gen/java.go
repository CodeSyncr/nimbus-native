// Java generates the schema's types for Android hosts as one outer class
// named after the package (package proto → class Proto) in the given Java
// package. It needs space.nimbusgo.nativekit's WireReader / WireWriter.
//
// Java has no unsigned types: uint8/16 are int, uint32 is long, and uint64
// is long holding the unsigned bit pattern.
func Java(s *schema.Schema, javaPackage string) []byte {
	g := &javaGen{s: s}
	ns := namespace(s)
	g.p(0, "// Code generated by nimbus native gen. DO NOT EDIT.")
	g.p(0, "// Schema: %s", s.Dir)
	g.p(0, "package %s;", javaPackage)
	g.p(0, "")
	g.p(0, "import space.nimbusgo.nativekit.WireException;")
	g.p(0, "import space.nimbusgo.nativekit.WireReader;")
	g.p(0, "import space.nimbusgo.nativekit.WireWriter;")
	g.p(0, "")
	g.p(0, "public final class %s {", ns)
	g.p(1, "/** Identifies this schema's wire layout; must match the Go side. */")
	g.p(1, "public static final long SCHEMA_HASH = %#016xL;", s.Hash)
	g.p(0, "")
	g.p(1, "private %s() {}", ns)
	for _, e := range s.Enums {
		g.enum(e)
	}
	for _, st := range s.Structs {
		g.class(st)
	}
	for _, u := range s.Unions {
		g.union(u.Name, u.Doc, u.Variants)
	}
	g.union(schema.MessageUnion, "Any top-level message in this schema.", s.Messages)
	g.p(0, "")
	g.p(1, "/** The message's wire encoding: its id, then its fields. */")
	g.p(1, "public static byte[] encode(Message m) {")
	g.p(2, "WireWriter w = new WireWriter();")
	g.p(2, "writeMessage(w, m);")
	g.p(2, "return w.toByteArray();")
	g.p(1, "}")
	g.p(0, "")
	g.p(1, "/** Reads exactly one message; throws WireException on bad input. */")
	g.p(1, "public static Message decode(byte[] bytes) {")
	g.p(2, "WireReader r = new WireReader(bytes);")
	g.p(2, "Message m = readMessage(r);")
	g.p(2, "r.done();")
	g.p(2, `if (m == null) throw new WireException("no message");`)
	g.p(2, "return m;")
	g.p(1, "}")
	g.p(0, "}")
	return []byte(g.b.String())
}

// JavaSchema generates the class holding the combined schema hash a host
// passes to Bridge.start.
func JavaSchema(javaPackage string, combined uint64) []byte {
	return []byte(fmt.Sprintf(`// Code generated by nimbus native gen. DO NOT EDIT.
package %s;

/** The combined hash of every wire schema linked into this app; pass it to Bridge.start. */
public final class NimbusSchema {
    public static final long COMBINED = %#016xL;

    private NimbusSchema() {}
}
`, javaPackage, combined))
}

type javaGen struct {
	s *schema.Schema
	b strings.Builder
}

func (g *javaGen) p(indent int, format string, args ...any) {
	if format != "" {
		g.b.WriteString(strings.Repeat("    ", indent))
		fmt.Fprintf(&g.b, format, args...)
	}
	g.b.WriteByte('\n')
}

func (g *javaGen) doc(indent int, doc string) {
	if doc != "" {
		g.p(indent, "/** %s */", strings.ReplaceAll(strings.ReplaceAll(doc, "*/", "* /"), "\n", " "))
	}
}

func (g *javaGen) enum(e *schema.EnumDef) {
	t := &schema.Type{Kind: schema.Int, Bits: e.Bits}
	if !e.Signed {
		t.Kind = schema.Uint
	}
	jt := javaType(t, false)
	g.p(0, "")
	g.doc(1, e.Doc)
	g.p(1, "public static final class %s {", e.Name)
	g.p(2, "private %s() {}", e.Name)
	for _, v := range e.Values {
		lit := fmt.Sprint(v.Value)
		if !e.Signed {
			lit = fmt.Sprint(uint64(v.Value))
			if e.Bits == 64 {
				lit = fmt.Sprintf("%#xL", uint64(v.Value))
			}
		}
		if jt == "long" && !strings.HasSuffix(lit, "L") {
			lit += "L"
		}
		cast := ""
		if jt == "byte" || jt == "short" {
			cast = "(" + jt + ") "
		}
		g.p(2, "public static final %s %s = %s%s;", jt, upperSnake(enumConst(e, v)), cast, lit)
	}
	g.p(1, "}")
}

func (g *javaGen) class(st *schema.StructDef) {
	var implements []string
	for _, u := range g.s.Unions {
		for _, v := range u.Variants {
			if v == st.Name {
				implements = append(implements, u.Name)
			}
		}
	}
	if st.Message {
		implements = append(implements, schema.MessageUnion)
	}
	impl := ""
	if len(implements) > 0 {
		impl = " implements " + strings.Join(implements, ", ")
	}
	g.p(0, "")
	g.doc(1, st.Doc)
	g.p(1, "public static final class %s%s {", st.Name, impl)
	for _, f := range st.Fields {
		def := javaDefault(f.Type)
		if def != "" {
			def = " = " + def
		}
		g.p(2, "public %s %s%s;", javaType(f.Type, false), javaName(f.Name), def)
	}
	g.p(0, "")
	g.p(2, "public void write(WireWriter w) {")
	for _, f := range st.Fields {
		g.write(3, f.Type, "this."+javaName(f.Name), 0)
	}
	g.p(2, "}")
	g.p(0, "")
	g.p(2, "public static %s read(WireReader r0) {", st.Name)
	g.p(3, "%s m = new %s();", st.Name, st.Name)
	for _, f := range st.Fields {
		g.p(3, "m.%s = %s;", javaName(f.Name), javaRead(f.Type, 0))
	}
	g.p(3, "return m;")
	g.p(2, "}")
	g.p(1, "}")
}

func (g *javaGen) union(name, doc string, variants []string) {
	g.p(0, "")
	g.doc(1, doc)
	g.p(1, "public interface %s {}", name)
	g.p(0, "")
	g.p(1, "public static void write%s(WireWriter w, %s v) {", name, name)
	g.p(2, "if (v == null) {")
	g.p(3, "w.uint(0);")
	for i, v := range variants {
		g.p(2, "} else if (v instanceof %s) {", v)
		g.p(3, "w.uint(%d);", i+1)
		g.p(3, "((%s) v).write(w);", v)
	}
	g.p(2, "} else {")
	g.p(3, `throw new IllegalArgumentException(v.getClass().getName() + " is not a %s variant");`, name)
	g.p(2, "}")
	g.p(1, "}")
	g.p(0, "")
	g.p(1, "public static %s read%s(WireReader r0) {", name, name)
	g.p(2, "long i = r0.uint();")
	g.p(2, "if (i == 0) return null;")
	for i, v := range variants {
		g.p(2, "if (i == %d) return %s.read(r0);", i+1, v)
	}
	g.p(2, `throw new WireException("unknown %s variant " + i);`, name)
	g.p(1, "}")
}

func (g *javaGen) write(indent int, t *schema.Type, x string, depth int) {
	switch t.Kind {
	case schema.Bool:
		g.p(indent, "w.bool(%s);", x)
	case schema.Uint:
		g.p(indent, "w.uint(%s);", x)
	case schema.Int:
		g.p(indent, "w.sint(%s);", x)
	case schema.Float32:
		g.p(indent, "w.f32(%s);", x)
	case schema.Float64:
		g.p(indent, "w.f64(%s);", x)
	case schema.String:
		g.p(indent, "w.string(%s);", x)
	case schema.Bytes:
		g.p(indent, "w.bytes(%s);", x)
	case schema.Enum:
		if t.Signed {
			g.p(indent, "w.sint(%s);", x)
		} else {
			g.p(indent, "w.uint(%s);", x)
		}
	case schema.Struct:
		g.p(indent, "%s.write(w);", x)
	case schema.Union:
		g.p(indent, "write%s(w, %s);", t.Name, x)
	case schema.Optional:
		g.p(indent, "if (%s == null) {", x)
		g.p(indent+1, "w.bool(false);")
		g.p(indent, "} else {")
		g.p(indent+1, "w.bool(true);")
		g.write(indent+1, t.Elem, x, depth+1)
		g.p(indent, "}")
	case schema.List:
		v := fmt.Sprintf("v%d", depth)
		g.p(indent, "w.uint(%s.size());", x)
		g.p(indent, "for (%s %s : %s) {", javaType(t.Elem, true), v, x)
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "}")
	case schema.Map:
		k, v, keys := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth), fmt.Sprintf("keys%d", depth)
		kt := javaType(t.Key, true)
		g.p(indent, "{")
		g.p(indent+1, "w.uint(%s.size());", x)
		g.p(indent+1, "java.util.List<%s> %s = new java.util.ArrayList<>(%s.keySet());", kt, keys, x)
		g.p(indent+1, "%s.sort(%s);", keys, javaKeyOrder(t.Key))
		g.p(indent+1, "for (%s %s : %s) {", kt, k, keys)
		g.write(indent+2, t.Key, k, depth+1)
		g.p(indent+2, "%s %s = %s.get(%s);", javaType(t.Elem, true), v, x, k)
		g.write(indent+2, t.Elem, v, depth+1)
		g.p(indent+1, "}")
		g.p(indent, "}")
	}
}

func javaKeyOrder(t *schema.Type) string {
	switch {
	case t.Kind == schema.String:
		return "WireWriter::compareUtf8"
	case t.Kind == schema.Uint && t.Bits == 64:
		return "Long::compareUnsigned"
	}
	return "java.util.Comparator.naturalOrder()"
}

// javaRead is an expression reading t from the WireReader named r<depth>.
func javaRead(t *schema.Type, depth int) string {
	r := fmt.Sprintf("r%d", depth)
	switch t.Kind {
	case schema.Bool:
		return r + ".bool()"
	case schema.Uint:
		switch t.Bits {
		case 64:
			return r + ".uint()"
		case 32:
			return r + ".uintMax(4294967295L)"
		}
		return fmt.Sprintf("(int) %s.uintMax(%dL)", r, uint64(1)<<t.Bits-1)
	case schema.Int:
		if t.Bits == 64 {
			return r + ".sint()"
		}
		return fmt.Sprintf("(%s) %s.intRange(%dL, %dL)", javaType(t, false), r, -(int64(1) << (t.Bits - 1)), int64(1)<<(t.Bits-1)-1)
	case schema.Float32:
		return r + ".f32()"
	case schema.Float64:
		return r + ".f64()"
	case schema.String:
		return r + ".string()"
	case schema.Bytes:
		return r + ".bytes()"
	case schema.Enum:
		base := &schema.Type{Kind: schema.Uint, Bits: t.Bits}
		if t.Signed {
			base.Kind = schema.Int
		}
		return javaRead(base, depth)
	case schema.Struct:
		return fmt.Sprintf("%s.read(%s)", t.Name, r)
	case schema.Union:
		return fmt.Sprintf("read%s(%s)", t.Name, r)
	case schema.Optional:
		// Box primitives explicitly so the conditional's type is the boxed one.
		cast := ""
		if javaType(t.Elem, true) != javaType(t.Elem, false) {
			cast = "(" + javaType(t.Elem, true) + ") "
		}
		return fmt.Sprintf("(%s.bool() ? %s%s : null)", r, cast, javaRead(t.Elem, depth))
	case schema.List:
		next := fmt.Sprintf("r%d", depth+1)
		return fmt.Sprintf("%s.<%s>list(%s -> %s)", r, javaType(t.Elem, true), next, javaRead(t.Elem, depth+1))
	case schema.Map:
		next := fmt.Sprintf("r%d", depth+1)
		return fmt.Sprintf("%s.<%s, %s>map(%s -> %s, %s -> %s)", r, javaType(t.Key, true), javaType(t.Elem, true),
			next, javaRead(t.Key, depth+1), next, javaRead(t.Elem, depth+1))
	}
	panic("unreachable")
}

func javaType(t *schema.Type, boxed bool) string {
	pick := func(prim, box string) string {
		if boxed {
			return box
		}
		return prim
	}
	switch t.Kind {
	case schema.Bool:
		return pick("boolean", "Boolean")
	case schema.Uint:
		if t.Bits <= 16 {
			return pick("int", "Integer")
		}
		return pick("long", "Long")
	case schema.Int:
		switch t.Bits {
		case 8:
			return pick("byte", "Byte")
		case 16:
			return pick("short", "Short")
		case 32:
			return pick("int", "Integer")
		}
		return pick("long", "Long")
	case schema.Float32:
		return pick("float", "Float")
	case schema.Float64:
		return pick("double", "Double")
	case schema.String:
		return "String"
	case schema.Bytes:
		return "byte[]"
	case schema.List:
		return "java.util.List<" + javaType(t.Elem, true) + ">"
	case schema.Map:
		return "java.util.Map<" + javaType(t.Key, true) + ", " + javaType(t.Elem, true) + ">"
	case schema.Optional:
		return javaType(t.Elem, true)
	case schema.Enum:
		base := &schema.Type{Kind: schema.Uint, Bits: t.Bits}
		if t.Signed {
			base.Kind = schema.Int
		}
		return javaType(base, boxed)
	}
	return t.Name // Struct, Union
}

func javaDefault(t *schema.Type) string {
	switch t.Kind {
	case schema.String:
		return `""`
	case schema.Bytes:
		return "new byte[0]"
	case schema.List:
		return "new java.util.ArrayList<>()"
	case schema.Map:
		return "new java.util.HashMap<>()"
	case schema.Struct:
		return "new " + t.Name + "()"
	}
	return "" // primitives default to 0 / false; optionals and unions to null
}
