// Kotlin generates the schema's types for Android hosts as one object named
// after the package (package proto → object Proto) in the given Kotlin
// package: data classes for structs, sealed interfaces for unions, constant
// objects for enums. It needs space.nimbusgo.nativekit's WireReader /
// WireWriter.
//
// Integers keep their size and sign where Kotlin can (Byte, Short, Int,
// Long); unsigned ones widen: uint8/16 → Int, uint32 → Long, and uint64 is a
// Long holding the unsigned bit pattern.
func Kotlin(s *schema.Schema, kotlinPackage string) []byte {
	g := &kotlinGen{s: s}
	ns := namespace(s)
	g.p(0, "// Code generated by nimbus native gen. DO NOT EDIT.")
	g.p(0, "@file:Suppress(\"unused\", \"ArrayInDataClass\", \"RedundantExplicitType\")")
	g.p(0, "")
	g.p(0, "package %s", kotlinPackage)
	g.p(0, "")
	if kotlinPackage != kitPackage {
		g.p(0, "import %s.WireException", kitPackage)
		g.p(0, "import %s.WireReader", kitPackage)
		g.p(0, "import %s.WireWriter", kitPackage)
		g.p(0, "")
	}
	g.p(0, "object %s {", ns)
	g.p(1, "/** Identifies this schema's wire layout; must match the Go side. */")
	g.p(1, "val SCHEMA_HASH: Long = %#016xuL.toLong()", s.Hash)
	for _, e := range s.Enums {
		g.enum(e)
	}
	for _, st := range s.Structs {
		g.class(st)
	}
	for _, u := range s.Unions {
		g.union(u.Name, u.Doc, u.Variants)
	}
	g.union(schema.MessageUnion, "Any top-level message in this schema.", s.Messages)
	g.p(0, "")
	g.p(1, "/** The message's wire encoding: its id, then its fields. */")
	g.p(1, "fun encode(m: Message): ByteArray {")
	g.p(2, "val w = WireWriter()")
	g.p(2, "writeMessage(w, m)")
	g.p(2, "return w.toByteArray()")
	g.p(1, "}")
	g.p(0, "")
	g.p(1, "/** Reads exactly one message; throws WireException on bad input. */")
	g.p(1, "fun decode(bytes: ByteArray): Message {")
	g.p(2, "val r = WireReader(bytes)")
	g.p(2, "val m = readMessage(r)")
	g.p(2, "r.done()")
	g.p(2, `return m ?: throw WireException("no message")`)
	g.p(1, "}")
	g.p(0, "}")
	return []byte(g.b.String())
}

// kitPackage holds the wire runtime and the framework's own schemas.
const kitPackage = "space.nimbusgo.nativekit"

// KotlinSchema generates the object holding the combined schema hash a host
// passes to Bridge.start.
func KotlinSchema(kotlinPackage string, combined uint64) []byte {
	return []byte(fmt.Sprintf(`// Code generated by nimbus native gen. DO NOT EDIT.

package %s

/** The combined hash of every wire schema linked into this app; pass it to Bridge.start. */
object NimbusSchema {
    val COMBINED: Long = %#016xuL.toLong()
}
`, kotlinPackage, combined))
}

type kotlinGen struct {
	s *schema.Schema
	b strings.Builder
}

func (g *kotlinGen) p(indent int, format string, args ...any) {
	if format != "" {
		g.b.WriteString(strings.Repeat("    ", indent))
		fmt.Fprintf(&g.b, format, args...)
	}
	g.b.WriteByte('\n')
}

func (g *kotlinGen) doc(indent int, doc string) {
	if doc != "" {
		g.p(indent, "/** %s */", strings.ReplaceAll(strings.ReplaceAll(doc, "*/", "* /"), "\n", " "))
	}
}

func (g *kotlinGen) enum(e *schema.EnumDef) {
	t := &schema.Type{Kind: schema.Int, Bits: e.Bits}
	if !e.Signed {
		t.Kind = schema.Uint
	}
	kt := kotlinType(t)
	g.p(0, "")
	g.doc(1, e.Doc)
	g.p(1, "object %s {", e.Name)
	for _, v := range e.Values {
		var lit string
		switch kt {
		case "Long":
			lit = fmt.Sprintf("%#xuL.toLong()", uint64(v.Value))
			if e.Signed {
				lit = fmt.Sprintf("%dL", v.Value)
			}
			g.p(2, "val %s: Long = %s", upperSnake(enumConst(e, v)), lit)
			continue
		case "Byte", "Short":
			lit = fmt.Sprintf("(%d).to%s()", v.Value, kt) // parenthesised: -1.toShort() is -(1.toShort()), an Int
			g.p(2, "val %s: %s = %s", upperSnake(enumConst(e, v)), kt, lit)
			continue
		}
		g.p(2, "const val %s: %s = %d", upperSnake(enumConst(e, v)), kt, v.Value)
	}
	g.p(1, "}")
}

func (g *kotlinGen) class(st *schema.StructDef) {
	var supers []string
	for _, u := range g.s.Unions {
		for _, v := range u.Variants {
			if v == st.Name {
				supers = append(supers, u.Name)
			}
		}
	}
	if st.Message {
		supers = append(supers, schema.MessageUnion)
	}
	impl := ""
	if len(supers) > 0 {
		impl = " : " + strings.Join(supers, ", ")
	}
	g.p(0, "")
	g.doc(1, st.Doc)
	g.p(1, "data class %s(", st.Name)
	for _, f := range st.Fields {
		g.p(2, "var %s: %s = %s,", kotlinName(f.Name), kotlinType(f.Type), kotlinDefault(f.Type))
	}
	g.p(1, ")%s {", impl)
	g.p(2, "fun write(w: WireWriter) {")
	for _, f := range st.Fields {
		g.write(3, f.Type, "this."+kotlinName(f.Name), 0) // "this.": a field may be named w
	}
	g.p(2, "}")
	g.p(0, "")
	g.p(2, "companion object {")
	g.p(3, "fun read(r0: WireReader): %s {", st.Name)
	g.p(4, "val m = %s()", st.Name)
	for _, f := range st.Fields {
		g.p(4, "m.%s = %s", kotlinName(f.Name), kotlinRead(f.Type, 0))
	}
	g.p(4, "return m")
	g.p(3, "}")
	g.p(2, "}")
	g.p(1, "}")
}

func (g *kotlinGen) union(name, doc string, variants []string) {
	g.p(0, "")
	g.doc(1, doc)
	g.p(1, "sealed interface %s", name)
	g.p(0, "")
	g.p(1, "fun write%s(w: WireWriter, v: %s?) {", name, name)
	g.p(2, "when (v) {")
	g.p(3, "null -> w.uint(0)")
	for i, v := range variants {
		g.p(3, "is %s -> { w.uint(%d); v.write(w) }", v, i+1)
	}
	g.p(2, "}")
	g.p(1, "}")
	g.p(0, "")
	g.p(1, "fun read%s(r0: WireReader): %s? = when (val i = r0.uint()) {", name, name)
	g.p(2, "0L -> null")
	for i, v := range variants {
		g.p(2, "%dL -> %s.read(r0)", i+1, v)
	}
	g.p(2, `else -> throw WireException("unknown %s variant $i")`, name)
	g.p(1, "}")
}

func (g *kotlinGen) write(indent int, t *schema.Type, x string, depth int) {
	switch t.Kind {
	case schema.Bool:
		g.p(indent, "w.bool(%s)", x)
	case schema.Uint:
		if t.Bits <= 16 {
			g.p(indent, "w.uint(%s.toLong())", x)
		} else {
			g.p(indent, "w.uint(%s)", x)
		}
	case schema.Int:
		g.p(indent, "w.sint(%s.toLong())", x)
	case schema.Float32:
		g.p(indent, "w.f32(%s)", x)
	case schema.Float64:
		g.p(indent, "w.f64(%s)", x)
	case schema.String:
		g.p(indent, "w.string(%s)", x)
	case schema.Bytes:
		g.p(indent, "w.bytes(%s)", x)
	case schema.Enum:
		base := &schema.Type{Kind: schema.Uint, Bits: t.Bits}
		if t.Signed {
			base.Kind = schema.Int
		}
		g.write(indent, base, x, depth)
	case schema.Struct:
		g.p(indent, "%s.write(w)", x)
	case schema.Union:
		g.p(indent, "write%s(w, %s)", t.Name, x)
	case schema.Optional:
		o := fmt.Sprintf("o%d", depth)
		g.p(indent, "run {") // a scope per optional, so each can name its local o<depth>
		g.p(indent+1, "val %s = %s", o, x)
		g.p(indent+1, "if (%s == null) w.bool(false) else {", o)
		g.p(indent+2, "w.bool(true)")
		g.write(indent+2, t.Elem, o, depth+1)
		g.p(indent+1, "}")
		g.p(indent, "}")
	case schema.List:
		v := fmt.Sprintf("v%d", depth)
		g.p(indent, "w.uint(%s.size.toLong())", x)
		g.p(indent, "for (%s in %s) {", v, x)
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "}")
	case schema.Map:
		k, v := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth)
		g.p(indent, "w.uint(%s.size.toLong())", x)
		g.p(indent, "for (%s in %s) {", k, kotlinSortedKeys(t.Key, x))
		g.write(indent+1, t.Key, k, depth+1)
		g.p(indent+1, "val %s = %s.getValue(%s)", v, x, k)
		g.write(indent+1, t.Elem, v, depth+1)
		g.p(indent, "}")
	}
}

// kotlinSortedKeys orders map keys as Go does: strings by UTF-8 bytes,
// uint64 unsigned, everything else numerically.
func kotlinSortedKeys(key *schema.Type, x string) string {
	switch {
	case key.Kind == schema.String:
		return x + ".keys.sortedWith(WireWriter.UTF8_ORDER)"
	case key.Kind == schema.Uint && key.Bits == 64:
		return x + ".keys.sortedWith { a, b -> java.lang.Long.compareUnsigned(a, b) }"
	}
	return x + ".keys.sorted()"
}

// kotlinRead is an expression reading t from the WireReader named r<depth>.
func kotlinRead(t *schema.Type, depth int) string {
	r := fmt.Sprintf("r%d", depth)
	switch t.Kind {
	case schema.Bool:
		return r + ".bool()"
	case schema.Uint:
		switch t.Bits {
		case 64:
			return r + ".uint()"
		case 32:
			return r + ".uintMax(4294967295L)"
		}
		return fmt.Sprintf("%s.uintMax(%dL).toInt()", r, uint64(1)<<t.Bits-1)
	case schema.Int:
		lo, hi := -(int64(1) << (t.Bits - 1)), int64(1)<<(t.Bits-1)-1
		switch t.Bits {
		case 64:
			return r + ".sint()"
		case 32:
			return fmt.Sprintf("%s.intRange(%dL, %dL).toInt()", r, lo, hi)
		}
		return fmt.Sprintf("%s.intRange(%dL, %dL).to%s()", r, lo, hi, kotlinType(t))
	case schema.Float32:
		return r + ".f32()"
	case schema.Float64:
		return r + ".f64()"
	case schema.String:
		return r + ".string()"
	case schema.Bytes:
		return r + ".bytes()"
	case schema.Enum:
		base := &schema.Type{Kind: schema.Uint, Bits: t.Bits}
		if t.Signed {
			base.Kind = schema.Int
		}
		return kotlinRead(base, depth)
	case schema.Struct:
		return fmt.Sprintf("%s.read(%s)", t.Name, r)
	case schema.Union:
		return fmt.Sprintf("read%s(%s)", t.Name, r)
	case schema.Optional:
		return fmt.Sprintf("(if (%s.bool()) %s else null)", r, kotlinRead(t.Elem, depth))
	case schema.List:
		next := fmt.Sprintf("r%d", depth+1)
		return fmt.Sprintf("%s.list { %s -> %s }", r, next, kotlinRead(t.Elem, depth+1))
	case schema.Map:
		next := fmt.Sprintf("r%d", depth+1)
		return fmt.Sprintf("%s.map({ %s -> %s }, { %s -> %s })", r, next, kotlinRead(t.Key, depth+1), next, kotlinRead(t.Elem, depth+1))
	}
	panic("unreachable")
}

func kotlinType(t *schema.Type) string {
	switch t.Kind {
	case schema.Bool:
		return "Boolean"
	case schema.Uint:
		if t.Bits <= 16 {
			return "Int"
		}
		return "Long"
	case schema.Int:
		switch t.Bits {
		case 8:
			return "Byte"
		case 16:
			return "Short"
		case 32:
			return "Int"
		}
		return "Long"
	case schema.Float32:
		return "Float"
	case schema.Float64:
		return "Double"
	case schema.String:
		return "String"
	case schema.Bytes:
		return "ByteArray"
	case schema.List:
		return "MutableList<" + kotlinType(t.Elem) + ">"
	case schema.Map:
		return "MutableMap<" + kotlinType(t.Key) + ", " + kotlinType(t.Elem) + ">"
	case schema.Optional:
		return kotlinType(t.Elem) + "?"
	case schema.Union:
		return t.Name + "?"
	case schema.Enum:
		base := &schema.Type{Kind: schema.Uint, Bits: t.Bits}
		if t.Signed {
			base.Kind = schema.Int
		}
		return kotlinType(base)
	}
	return t.Name // Struct
}

func kotlinDefault(t *schema.Type) string {
	switch t.Kind {
	case schema.Bool:
		return "false"
	case schema.Uint, schema.Int, schema.Enum:
		if kotlinType(t) == "Long" {
			return "0L"
		}
		return "0"
	case schema.Float32:
		return "0f"
	case schema.Float64:
		return "0.0"
	case schema.String:
		return `""`
	case schema.Bytes:
		return "ByteArray(0)"
	case schema.List:
		return "mutableListOf()"
	case schema.Map:
		return "mutableMapOf()"
	case schema.Optional, schema.Union:
		return "null"
	}
	return t.Name + "()"
}
